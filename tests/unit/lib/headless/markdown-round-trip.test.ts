/** Marks with no Markdown form: the text stays, the mark goes. */
const DROPPED_MARKS = new Set(["textColor", "fontSize"]);

/**
 * Attributes Markdown has no syntax for, per node type. Heading ids are
 * regenerated by the editor; alignment, media layout and captions have no
 * Markdown form. Media keep `src`; images keep `alt`, `title` and `width`.
 */
const DROPPED_ATTRS: Record<string, readonly string[]> = {
  heading: ["id", "data-toc-id", "textAlign"],
  paragraph: ["textAlign"],
  tableCell: ["align", "colwidth"],
  tableHeader: ["align", "colwidth"],
};

const MEDIA_NODES = new Set([
  "audio",
  "loom",
  "soundcloud",
  "spotify",
  "video",
  "vimeo",
  "x",
  "youtube",
]);

/**
 * What the media kit's `![alt](src "caption"){…}` form keeps. A link's or
 * image's hover `title`, `margin` and embed options (`start`, `autoplay`…)
 * are lost.
 */
const KEPT_MEDIA_ATTRS = new Set([
  "src",
  "caption",
  "width",
  "height",
  "float",
  "display",
  "clear",
]);
const KEPT_IMAGE_ATTRS = new Set([...KEPT_MEDIA_ATTRS, "alt"]);

/**
 * The documented degradation (docs/design/2026-11-22-markdown-mapping.md), applied to
 * a document: what a Markdown export then import must give back exactly.
 */
function normalizeForMarkdown(node: JSONContent): JSONContent | null {
  if (node.type === "imageUpload") return null;
  const out: JSONContent = { type: node.type };
  if (node.attrs) {
    const attrs = { ...node.attrs };
    for (const name of DROPPED_ATTRS[node.type ?? ""] ?? []) delete attrs[name];
    const kept =
      node.type === "image"
        ? KEPT_IMAGE_ATTRS
        : MEDIA_NODES.has(node.type ?? "")
          ? KEPT_MEDIA_ATTRS
          : null;
    if (kept) {
      for (const name of Object.keys(attrs)) {
        if (!kept.has(name)) delete attrs[name];
      }
    }
    out.attrs = attrs;
  }
  if (node.text !== undefined) out.text = node.text;
  if (node.marks) {
    const marks = node.marks
      .filter((mark) => !DROPPED_MARKS.has(mark.type))
      // Highlight colour has no Markdown form: `==text==` comes back in
      // the default token.
      .map((mark) => {
        if (mark.type === "highlight") {
          return {
            type: "highlight",
            attrs: { color: DEFAULT_HIGHLIGHT_TOKEN },
          };
        }
        // `[text](href)` has a title slot, but the link mark does not write it.
        if (mark.type === "hyperlink") {
          return { ...mark, attrs: { ...mark.attrs, title: null } };
        }
        return mark;
      });
    if (marks.length) out.marks = marks;
  }
  if (node.content) {
    out.content = node.content
      .map(normalizeForMarkdown)
      .filter((child): child is JSONContent => child !== null);
  }
  return out;
}

/** Schema-normalised JSON (defaults filled, adjacent text merged). */
function canonical(json: JSONContent): JSONContent {
  const node = getHeadlessSchema().nodeFromJSON(json);
  node.check();
  return node.toJSON() as JSONContent;
}

const FIXTURES: Record<string, JSONContent> = {
  "all nodes": ALL_NODES_DOC,
  "mixed content": mixedContent,
  "real-world complex": realWorldComplex,
  "deeply nested": deeplyNested,
  "title only": titleOnly,
  "empty document": emptyDocument,
  "wide document": wideDocument,
};

const META = {
  tags: ["planning", "Q4 review"],
  createdAt: Date.UTC(2026, 0, 2, 3, 4, 5),
  modifiedAt: Date.UTC(2026, 10, 20, 12, 30),
};

function roundTrip(doc: JSONContent) {
  const ydoc = jsonToYDoc(doc);
  const markdown = exportMarkdown(ydoc, META);
  const imported = importMarkdown(markdown, { fileName: "ignored.md" });
  return { ydoc, markdown, imported };
}

describe("Markdown round trip", () => {
  for (const [name, doc] of Object.entries(FIXTURES)) {
    it(`${name}: export then import keeps every surviving node`, () => {
      const { imported } = roundTrip(doc);
      expect(canonical(imported.doc)).toEqual(
        canonical(normalizeForMarkdown(canonical(doc)) as JSONContent),
      );
    });

    it(`${name}: a second export is identical (stable)`, () => {
      const { markdown, imported } = roundTrip(doc);
      const again = exportMarkdown(jsonToYDoc(imported.doc), META);
      expect(again).toBe(markdown);
    });

    it(`${name}: metadata survives through front matter`, () => {
      const { ydoc, imported } = roundTrip(doc);
      const title =
        getHeadlessSchema()
          .nodeFromJSON(yDocToJSON(ydoc))
          .firstChild?.textContent.trim() ?? "";
      expect(imported.title).toBe(title);
      expect(imported.tags).toEqual(META.tags);
      expect(imported.createdAt).toBe(META.createdAt);
      expect(imported.modifiedAt).toBe(META.modifiedAt);
      expect(imported.droppedProperties).toEqual([]);
    });
  }
});

const paragraphs = (...texts: string[]): JSONContent => ({
  type: "doc",
  content: [
    {
      type: "heading",
      attrs: { level: 1 },
      content: [{ type: "text", text: "T" }],
    },
    ...texts.map((text) => ({
      type: "paragraph",
      content: [{ type: "text", text }],
    })),
  ],
});

describe("Markdown escaping", () => {
  const literal = [
    "# not a heading",
    "1. not a list",
    "- not a bullet",
    "> not a quote",
    "---",
    "*not italic* and **not bold** and _x_",
    "`not code`",
    "[[Wikilink]] and [[Note|Alias]]",
    "[not a link](notes.md)",
    "<script>alert(1)</script>",
    "a | b | c",
    "~~not struck~~ ==not marked==",
    "back\\slash and trailing backslash\\",
    "&amp; stays literal",
    "+ not a bullet",
    "1) not a list",
    "===",
    "* * *",
    "    four leading spaces",
    "\ttab first",
    "![not an image](x.png)",
  ];
  for (const text of literal) {
    it(`keeps the literal text ${JSON.stringify(text)}`, () => {
      const { imported } = roundTrip(paragraphs(text));
      expect(canonical(imported.doc)).toEqual(canonical(paragraphs(text)));
    });
  }

  it("keeps a code block that contains a fence", () => {
    const doc: JSONContent = {
      type: "doc",
      content: [
        {
          type: "heading",
          attrs: { level: 1 },
          content: [{ type: "text", text: "T" }],
        },
        {
          type: "codeBlock",
          attrs: { language: "md" },
          content: [{ type: "text", text: "```js\nx\n```\n~~~" }],
        },
      ],
    };
    expect(canonical(roundTrip(doc).imported.doc)).toEqual(canonical(doc));
  });

  it("keeps inline code that contains a backtick", () => {
    const doc: JSONContent = {
      type: "doc",
      content: [
        {
          type: "heading",
          attrs: { level: 1 },
          content: [{ type: "text", text: "T" }],
        },
        {
          type: "paragraph",
          content: [
            { type: "text", text: "a`b", marks: [{ type: "inlineCode" }] },
          ],
        },
      ],
    };
    expect(canonical(roundTrip(doc).imported.doc)).toEqual(canonical(doc));
  });

  it("keeps a pipe inside a table cell", () => {
    const cell = (type: string, text: string) => ({
      type,
      content: [{ type: "paragraph", content: [{ type: "text", text }] }],
    });
    const doc: JSONContent = {
      type: "doc",
      content: [
        {
          type: "heading",
          attrs: { level: 1 },
          content: [{ type: "text", text: "T" }],
        },
        {
          type: "table",
          content: [
            { type: "tableRow", content: [cell("tableHeader", "a|b")] },
            { type: "tableRow", content: [cell("tableCell", "c|d")] },
          ],
        },
      ],
    };
    expect(canonical(roundTrip(doc).imported.doc)).toEqual(canonical(doc));
  });

  it("drops an unsafe code language on export", () => {
    const doc: JSONContent = {
      type: "doc",
      content: [
        {
          type: "heading",
          attrs: { level: 1 },
          content: [{ type: "text", text: "T" }],
        },
        {
          type: "codeBlock",
          attrs: { language: "x fixed inset-0" },
          content: [{ type: "text", text: "code" }],
        },
      ],
    };
    const { markdown, imported } = roundTrip(doc);
    expect(markdown).not.toContain("inset-0");
    expect(imported.doc.content?.[1]?.attrs?.language).toBeNull();
  });
});

const TITLE: JSONContent = {
  type: "heading",
  attrs: { level: 1 },
  content: [{ type: "text", text: "T" }],
};

const textParagraph = (text?: string): JSONContent =>
  text
    ? { type: "paragraph", content: [{ type: "text", text }] }
    : { type: "paragraph" };

const tableCell = (type: string, content: JSONContent[], attrs = {}) => ({
  type,
  attrs,
  content,
});

/** Body blocks after the title, schema-normalised. */
function importedBlocks(...blocks: JSONContent[]): JSONContent[] {
  const doc = { type: "doc", content: [TITLE, ...blocks] };
  return canonical(roundTrip(doc).imported.doc).content?.slice(1) ?? [];
}

describe("documented degradations", () => {
  it("keeps a line break and a block marker after it as text", () => {
    const blocks: JSONContent[] = [
      {
        type: "paragraph",
        content: [
          { type: "text", text: "a" },
          { type: "hardBreak" },
          { type: "text", text: "- b" },
          { type: "hardBreak" },
          { type: "text", text: "===" },
        ],
      },
    ];
    expect(importedBlocks(...blocks)).toEqual(
      canonical({ type: "doc", content: [TITLE, ...blocks] }).content?.slice(
        1,
      ) ?? [],
    );
  });

  it("keeps a heading ending in ` #`", () => {
    const heading: JSONContent = {
      type: "heading",
      attrs: { level: 2 },
      content: [{ type: "text", text: "Learn C #" }],
    };
    expect(importedBlocks(heading)[0]?.content?.[0]?.text).toBe("Learn C #");
  });

  it("turns an empty heading below the title into an empty paragraph", () => {
    expect(
      importedBlocks(
        { type: "heading", attrs: { level: 2 } },
        textParagraph("x"),
      ).map((node) => node.type),
    ).toEqual(["paragraph", "paragraph"]);
  });

  it("unmerges merged cells, keeping the text in the first one", () => {
    const [table] = importedBlocks({
      type: "table",
      content: [
        {
          type: "tableRow",
          content: [
            tableCell("tableHeader", [textParagraph("a")], { colspan: 2 }),
          ],
        },
        {
          type: "tableRow",
          content: [
            tableCell("tableCell", [textParagraph("b")]),
            tableCell("tableCell", [textParagraph("c")]),
          ],
        },
      ],
    });
    const header = table.content?.[0]?.content ?? [];
    expect(header.map((cell) => cell.attrs?.colspan)).toEqual([1, 1]);
    expect(header.map((cell) => cell.content?.[0]?.content?.[0]?.text)).toEqual(
      ["a", undefined],
    );
  });

  it("joins a cell's blocks into one paragraph with line breaks", () => {
    const [table] = importedBlocks({
      type: "table",
      content: [
        {
          type: "tableRow",
          content: [tableCell("tableHeader", [textParagraph("h")])],
        },
        {
          type: "tableRow",
          content: [
            tableCell("tableCell", [
              textParagraph("one"),
              textParagraph("two"),
            ]),
          ],
        },
      ],
    });
    expect(table.content?.[1]?.content?.[0]?.content).toEqual([
      {
        type: "paragraph",
        attrs: { textAlign: null },
        content: [
          { type: "text", text: "one" },
          { type: "hardBreak" },
          { type: "text", text: "two" },
        ],
      },
    ]);
  });

  it("gives a table without a header row an empty header row", () => {
    const [table] = importedBlocks({
      type: "table",
      content: [
        {
          type: "tableRow",
          content: [
            tableCell("tableCell", [textParagraph("x")]),
            tableCell("tableCell", [textParagraph("y")]),
          ],
        },
      ],
    });
    expect(table.content?.map((row) => row.content?.[0]?.type)).toEqual([
      "tableHeader",
      "tableCell",
    ]);
    expect(
      table.content?.[1]?.content?.map(
        (cell) => cell.content?.[0]?.content?.[0]?.text,
      ),
    ).toEqual(["x", "y"]);
  });
});

describe("exportMarkdown", () => {
  it("starts with front matter and repeats the title as the first heading", () => {
    const markdown = exportMarkdown(jsonToYDoc(paragraphs("Body")), {
      tags: [],
    });
    expect(markdown).toBe('---\ntitle: "T"\ntags: []\n---\n\n# T\n\nBody\n');
  });

  it("reads only the document fragment, never other shared types", () => {
    const ydoc = jsonToYDoc(paragraphs("Body"));
    ydoc.getMap("comments").set("c1", "secret comment");
    ydoc.getMap("share").set("token", "s3cr3t-token");
    const markdown = exportMarkdown(ydoc, { tags: [] });
    expect(markdown).not.toContain("secret comment");
    expect(markdown).not.toContain("s3cr3t-token");
  });

  it("exports a never-opened (empty) document", () => {
    expect(exportMarkdown(new Y.Doc(), { tags: [] })).toBe(
      '---\ntitle: ""\ntags: []\n---\n',
    );
  });

  it("uses the title's text with hard breaks as spaces", () => {
    const ydoc = jsonToYDoc({
      type: "doc",
      content: [
        {
          type: "heading",
          attrs: { level: 1 },
          content: [
            { type: "text", text: "Two" },
            { type: "hardBreak" },
            { type: "text", text: "lines" },
          ],
        },
      ],
    });
    expect(exportMarkdown(ydoc, { tags: [] })).toStartWith(
      '---\ntitle: "Two lines"\n',
    );
  });
});

describe("importMarkdown", () => {
  it("takes the title from front matter, then a leading H1, then the file name", () => {
    expect(importMarkdown("---\ntitle: Front\n---\nText").title).toBe("Front");
    expect(importMarkdown("# Heading\n\nText").title).toBe("Heading");
    expect(importMarkdown("Text", { fileName: "notes.md" }).title).toBe(
      "notes",
    );
    expect(importMarkdown("Text").title).toBe("");
  });

  it("does not repeat a leading H1 that equals the title", () => {
    const { doc } = importMarkdown("---\ntitle: Same\n---\n# Same\n\nText");
    expect(doc.content?.map((node) => node.type)).toEqual([
      "heading",
      "paragraph",
    ]);
  });

  it("keeps a leading H1 that differs from the title below it", () => {
    const { doc } = importMarkdown("---\ntitle: Front\n---\n# Other\n\nText");
    expect(doc.content?.map((node) => node.content?.[0]?.text)).toEqual([
      "Front",
      "Other",
      "Text",
    ]);
  });

  it("reads tags as a list or a comma string, capped like the library", () => {
    expect(importMarkdown('---\ntags: "a, #b, A"\n---\n').tags).toEqual([
      "a",
      "b",
    ]);
    const many = Array.from({ length: 25 }, (_, i) => `t${i}`);
    const long = "x".repeat(41);
    const read = importMarkdown(
      `---\ntags: [${[...many, long].join(", ")}]\n---\n`,
    );
    expect(read.tags).toEqual(many.slice(0, 20));
    expect(read.droppedTags).toBe(6);
  });

  it("reads date and updated as created and modified", () => {
    const read = importMarkdown(
      "---\ndate: 2024-05-01\nupdated: 2024-06-01T10:00:00Z\n---\n",
    );
    expect(read.createdAt).toBe(Date.UTC(2024, 4, 1));
    expect(read.modifiedAt).toBe(Date.UTC(2024, 5, 1, 10));
  });

  it("counts properties it does not keep", () => {
    const read = importMarkdown(
      "---\ntitle: T\naliases: [a]\ncssclass: wide\nbad: &x y\n---\n",
    );
    expect(read.droppedProperties.sort()).toEqual([
      "aliases",
      "bad",
      "cssclass",
    ]);
  });

  it("lifts embeds out of paragraphs so the result fits the schema", () => {
    const { doc } = importMarkdown(
      "# T\n\n![youtube](https://www.youtube.com/watch?v=dQw4w9WgXcQ)\n",
    );
    expect(doc.content?.map((node) => node.type)).toEqual([
      "heading",
      "youtube",
    ]);
  });
});
